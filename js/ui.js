  // Sanitize text for HTML injection safety
  escapeHTML(str) {
    if (!str && str !== 0) return '';
    return String(str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#039;');
  },

  // Toast Notification System
  showToast(message, type = 'success', title = '', duration = 3500) {
    const container = document.getElementById('toast-container');
    if (!container) return;

    const toast = document.createElement('div');
    toast.className = `sms-toast toast-${type}`;
    
    let iconSvg = UI.icons.check;
    if (type === 'error' || type === 'danger') iconSvg = UI.icons.x;
    if (type === 'warning') iconSvg = UI.icons.clock;
    if (type === 'info') iconSvg = UI.icons.bell;

    toast.innerHTML = `
      <div class="toast-icon">${iconSvg}</div>
      <div class="toast-content">
        ${title ? `<div class="toast-title">${UI.escapeHTML(title)}</div>` : ''}
        <div class="toast-message">${UI.escapeHTML(message)}</div>
      </div>
      <button class="toast-close" onclick="this.parentElement.remove()">&times;</button>
    `;

    container.appendChild(toast);

    // Auto dismiss
    setTimeout(() => {
      toast.classList.add('toast-fadeout');
      setTimeout(() => toast.remove(), 300);
    }, duration);
  },

  // Confirmation Modal
  confirm({ title = 'Confirm Action', message = 'Are you sure you want to proceed?', confirmText = 'Confirm', cancelText = 'Cancel', isDanger = true, onConfirm = () => {} }) {
    const modal = document.getElementById('confirm-modal');
    if (!modal) return;

    const titleEl = modal.querySelector('#confirm-modal-title');
    const msgEl = modal.querySelector('#confirm-modal-message');
    const okBtn = modal.querySelector('#confirm-modal-ok');
    const cancelBtn = modal.querySelector('#confirm-modal-cancel');

    if (titleEl) titleEl.textContent = title;
    if (msgEl) msgEl.innerHTML = message;
    if (okBtn) {
      okBtn.textContent = confirmText;
      okBtn.className = isDanger ? 'btn btn-danger' : 'btn btn-primary';
      
      // Remove old listeners
      const newOkBtn = okBtn.cloneNode(true);
      okBtn.parentNode.replaceChild(newOkBtn, okBtn);
      
      newOkBtn.addEventListener('click', () => {
        UI.closeModal('confirm-modal');
        if (typeof onConfirm === 'function') onConfirm();
      });
    }

    if (cancelBtn) {
      cancelBtn.textContent = cancelText;
    }

    UI.openModal('confirm-modal');
  },

  // Modal Open/Close helpers
  openModal(modalId) {
    const modal = document.getElementById(modalId);
    if (modal) {
      modal.classList.add('active');
      document.body.classList.add('modal-open');
    }
  },

  closeModal(modalId) {
    const modal = document.getElementById(modalId);
    if (modal) {
      modal.classList.remove('active');
      // Only remove modal-open if no other active modal
      if (!document.querySelector('.modal-wrapper.active')) {
        document.body.classList.remove('modal-open');
      }
    }
  },

  // Format date helper
  formatDate(dateStr) {
    if (!dateStr) return 'N/A';
    try {
      const d = new Date(dateStr);
      return d.toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric' });
    } catch (e) {
      return dateStr;
    }
  }
